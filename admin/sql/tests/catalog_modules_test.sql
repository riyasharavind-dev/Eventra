begin;
create temporary table catalog_checks(label text primary key);
create temporary table catalog_ids(name text primary key,id uuid);
grant select,insert on catalog_checks,catalog_ids to authenticated,anon;
create function pg_temp.catalog_ok(value boolean,label text) returns void language plpgsql as $$begin if value is distinct from true then raise exception 'FAILED: %',label;end if;insert into catalog_checks values(label);end $$;
insert into auth.users(id,email,raw_user_meta_data,email_confirmed_at) values('ec000000-0000-4000-8000-000000000021','catalog-owner@example.invalid','{"role":"admin"}',now());
insert into public.admins(id,name,access_level) values('ec000000-0000-4000-8000-000000000021','Catalog fixture','owner');
set local role authenticated;
select set_config('request.jwt.claims','{"sub":"ec000000-0000-4000-8000-000000000021","role":"authenticated","aal":"aal2"}',true);
do $$declare root jsonb;child jsonb;event_row jsonb;updated jsonb;catalog jsonb;blocked boolean:=false;begin
 catalog:=public.admin_catalog();
 perform pg_temp.catalog_ok((select count(*)=2 from jsonb_array_elements(catalog)x where x->>'name' in ('category_nodes','event_types') and (x->>'can_create')::boolean),'both catalog modules allow secure creation');
 root:=public.admin_save('category_nodes','{"name":"Catalog Test Parent","slug":"catalog-transaction-parent","parent_id":null}');
 child:=public.admin_save('category_nodes',jsonb_build_object('name','Catalog Test Child','slug','catalog-transaction-child','parent_id',root->>'id'));
 perform pg_temp.catalog_ok(child->>'parent_id'=root->>'id','admin creates child under selected parent');
 insert into catalog_ids values('root',(root->>'id')::uuid),('child',(child->>'id')::uuid);
 begin perform public.admin_save('category_nodes',jsonb_build_object('parent_id',child->>'id'),root->>'id',root->>'_revision');exception when raise_exception then blocked:=true;end;
 perform pg_temp.catalog_ok(blocked,'category cycle rejected');
 event_row:=public.admin_save('event_types','{"name":"Catalog Test Event","slug":"catalog-transaction-event","description":"Rollback fixture","is_active":true,"sort_order":7}');
 insert into catalog_ids values('event',(event_row->>'id')::uuid);
 perform pg_temp.catalog_ok((event_row->>'is_active')::boolean and (event_row->>'sort_order')::integer=7,'admin creates active event with display order');
 updated:=public.admin_save('event_types','{"description":"Updated catalog fixture"}',event_row->>'id',event_row->>'_revision');
 perform pg_temp.catalog_ok(updated->>'description'='Updated catalog fixture','admin edits event through audited RPC');
 event_row:=public.admin_save('event_types','{"name":"Catalog Hidden Event","slug":"catalog-transaction-hidden","is_active":false,"sort_order":8}');
 insert into catalog_ids values('hidden',(event_row->>'id')::uuid);
end $$;
reset role;
set local role anon;
select set_config('request.jwt.claims','{}',true);
select pg_temp.catalog_ok((select count(*)=2 from public.category_nodes where id in(select id from catalog_ids where name in ('root','child'))),'shared app reads see new category hierarchy');
select pg_temp.catalog_ok(exists(select 1 from public.event_types where id=(select id from catalog_ids where name='event')),'shared app reads see active event');
select pg_temp.catalog_ok(not exists(select 1 from public.event_types where id=(select id from catalog_ids where name='hidden')),'inactive event hidden from public app reads');
reset role;
select count(*) passed_catalog_checks from catalog_checks;
rollback;
